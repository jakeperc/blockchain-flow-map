/**
 * Writes lib/landmarks/data.ts, the numbers the Landmarks island needs (one point per leg, the protocol milestones,
 * the fixed windows and the field's value range). No prose: the stories are static HTML written by html.mjs, so
 * nothing is shipped twice. Refuses to write while build.mjs reports an error.
 *
 *   node scripts/landmarks/gen-landmarks.mjs
 *
 * verify-landmarks.mjs regenerates this text and fails when the committed file differs, so it cannot go stale.
 */
import {writeFileSync} from 'node:fs';
import {join} from 'node:path';
import {pathToFileURL} from 'node:url';
import {ROOT, loadInputs, buildModel, pointsOf} from './build.mjs';
import {decadesFor} from '../../lib/landmarks/field.ts';

export const DATA_FILE = 'lib/landmarks/data.ts';

/** The value range of the field: every THEN value and every TODAY value at the reference spot prices, padded. */
export function domainOf(model, points) {
  const ref = model.refPrices && model.refPrices.usd ? model.refPrices.usd : {};
  const today = points.filter((p) => p.todayApplicable && ref[p.asset]).map((p) => p.amount * ref[p.asset]);
  return decadesFor([...points.map((p) => p.usdThen), ...today]);
}

export function renderData(model) {
  const points = pointsOf(model);
  const domain = domainOf(model, points);
  const meta = {dataAsOf: model.dataAsOf, recent: model.recent, allTime: model.allTime};
  const milestones = model.milestones.map((m) => ({label: m.label, chain: m.chain, t: m.t}));
  const json = (v) => JSON.stringify(v, null, 1).replace(/\n\s*/g, ' ');
  return [
    '/* GENERATED by scripts/landmarks/gen-landmarks.mjs from scripts/landmarks/ (entries, chain-facts.json). Do not edit. */',
    "import type {LandmarkPoint, LandmarksMeta, Milestone} from './types';",
    '',
    `export const META: LandmarksMeta = ${json(meta)};`,
    `export const DOMAIN = ${json(domain)};`,
    `export const MILESTONES: Milestone[] = ${json(milestones)};`,
    'export const POINTS: LandmarkPoint[] = [',
    ...points.map((p) => `  ${json(p)},`),
    '];',
    '',
  ].join('\n');
}

if (process.argv[1] && import.meta.url === pathToFileURL(process.argv[1]).href) {
  const {model, errors, warnings} = buildModel(loadInputs(ROOT));
  warnings.forEach((w) => console.warn(`WARN ${w}`));
  if (errors.length) {
    console.error(`not written: ${errors.length} problem(s)\n  - ${errors.join('\n  - ')}`);
    process.exit(1);
  }
  writeFileSync(join(ROOT, DATA_FILE), renderData(model));
  console.log(`wrote ${DATA_FILE}: ${model.entries.length} entries, ${pointsOf(model).length} points`);
}
